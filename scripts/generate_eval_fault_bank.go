func demoResources(item generatedCase) []interface{} {
	faultType := item.Case.GoldenAnswer.ExpectedFaultType
	resources := []interface{}{}
	switch faultType {
	case "OOMKilled":
		resources = append(resources, oomDemoPod(item))
	case "CrashLoopBackOff":
		resources = append(resources, crashLoopDemoPod(item))
	case "PodPending":
		resources = append(resources, pendingDemoResources(item)...)
	case "ImagePullBackOff":
		resources = append(resources, imagePullDemoPod(item))
	case "ProbeFailed":
		resources = append(resources, probeDemoPod(item))
	case "InitError":
		resources = append(resources, initDemoPod(item))
	case "Evicted":
		resources = append(resources, evictedDemoPod(item))
	case "NodeNotReady":
		resources = append(resources, nodeNotReadyPlaceholderPod(item))
	default:
		resources = append(resources, unknownDemoPod(item))
	}
	if needsSyntheticEvents(item) {
		resources = append(resources, eventDemoResources(item)...)
	}
	return resources
}

