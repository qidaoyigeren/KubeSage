func firstAppContainer(item generatedCase) corev1.Container {
	if item.Ctx != nil && item.Ctx.Pod != nil && len(item.Ctx.Pod.Spec.Containers) > 0 {
		return item.Ctx.Pod.Spec.Containers[0]
	}
	return corev1.Container{Name: "app", Image: "busybox:1.36"}
}

func firstLogLine(item generatedCase) string {
	if item.Ctx == nil {
		return item.Case.GoldenAnswer.RootCause
	}
	for _, log := range item.Ctx.Logs {
		for _, text := range []string{log.Previous, log.Current, log.Loki} {
			text = strings.TrimSpace(text)
			if text != "" {
				return strings.Split(text, "\n")[0]
			}
		}
	}
	if len(item.Ctx.Events) > 0 {
		return item.Ctx.Events[0].Message
	}
	return item.Case.GoldenAnswer.RootCause
}

func resourcesMap(resources corev1.ResourceRequirements) map[string]interface{} {
	out := map[string]interface{}{}
	if len(resources.Requests) > 0 {
		out["requests"] = resourceListMap(resources.Requests)
	}
	if len(resources.Limits) > 0 {
		out["limits"] = resourceListMap(resources.Limits)
	}
	return out
}

func resourceListMap(list corev1.ResourceList) map[string]string {
	out := map[string]string{}
	for name, quantity := range list {
		out[string(name)] = quantity.String()
	}
	return out
}

func probeMap(probe *corev1.Probe) map[string]interface{} {
	if probe == nil || probe.HTTPGet == nil {
		return nil
	}
	port := interface{}(probe.HTTPGet.Port.IntVal)
	if probe.HTTPGet.Port.Type == intstr.String {
		port = probe.HTTPGet.Port.StrVal
	}
	return map[string]interface{}{
		"httpGet": map[string]interface{}{
			"path":   probe.HTTPGet.Path,
			"port":   port,
			"scheme": string(probe.HTTPGet.Scheme),
		},
		"initialDelaySeconds": probe.InitialDelaySeconds,
		"timeoutSeconds":      probe.TimeoutSeconds,
		"periodSeconds":       probe.PeriodSeconds,
		"failureThreshold":    probe.FailureThreshold,
	}
}

func probeCommand(item generatedCase) string {
	logLine := firstLogLine(item)
	switch {
	case strings.Contains(item.Case.ID, "refused"):
		return fmt.Sprintf("import time\nprint(%q, flush=True)\nwhile True:\n    time.sleep(30)\n", logLine)
	case strings.Contains(item.Case.ID, "timeout"), strings.Contains(item.Case.ID, "slow-startup"):
		return fmt.Sprintf("import time\nfrom http.server import BaseHTTPRequestHandler, HTTPServer\nclass H(BaseHTTPRequestHandler):\n    def do_GET(self):\n        print(%q, flush=True)\n        time.sleep(10)\n        self.send_response(200)\n        self.end_headers()\n        self.wfile.write(b'ok')\nHTTPServer(('0.0.0.0', 8080), H).serve_forever()\n", logLine)
	case strings.Contains(item.Case.ID, "503"):
		return fmt.Sprintf("from http.server import BaseHTTPRequestHandler, HTTPServer\nclass H(BaseHTTPRequestHandler):\n    def do_GET(self):\n        print(%q, flush=True)\n        self.send_response(503)\n        self.end_headers()\n        self.wfile.write(b'unavailable')\nHTTPServer(('0.0.0.0', 8080), H).serve_forever()\n", logLine)
	default:
		return fmt.Sprintf("from http.server import BaseHTTPRequestHandler, HTTPServer\nclass H(BaseHTTPRequestHandler):\n    def do_GET(self):\n        print(%q, flush=True)\n        self.send_response(404)\n        self.end_headers()\n        self.wfile.write(b'not found')\nHTTPServer(('0.0.0.0', 8080), H).serve_forever()\n", logLine)
	}
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "'\"'\"'") + "'"
}

func sanitizeEventName(name string) string {
	name = strings.ToLower(name)
	name = strings.NewReplacer("_", "-", ":", "-", "/", "-", " ", "-").Replace(name)
	return name
}

func fatalf(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
