func writeDemoManifests(cases []generatedCase) error {
	demoDir := filepath.Join("demo", "fault-bank")
	if err := os.MkdirAll(demoDir, 0o755); err != nil {
		return err
	}

	namespacePath := filepath.Join(demoDir, "namespace.yaml")
	if err := writeYAMLDocuments(namespacePath, []interface{}{namespaceManifest()}); err != nil {
		return err
	}

	resources := []interface{}{
		storageClassManifest(),
		demoNotesConfigMap(),
	}
	for _, item := range cases {
		resources = append(resources, demoResources(item)...)
	}
	if err := writeYAMLDocuments(filepath.Join(demoDir, "generated-manifests.yaml"), resources); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(demoDir, "kustomization.yaml"), []byte(demoKustomization()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(demoDir, "README.md"), []byte(demoReadme(len(cases))), 0o644)
}

func writeYAMLDocuments(path string, docs []interface{}) error {
	var b strings.Builder
	b.WriteString("# Generated by scripts/generate_eval_fault_bank.go; edit the generator and rerun.\n")
	for i, doc := range docs {
		if i > 0 {
			b.WriteString("---\n")
		}
		data, err := yaml.Marshal(doc)
		if err != nil {
			return fmt.Errorf("marshal document %d for %s: %w", i+1, path, err)
		}
		b.Write(data)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

