func main() {
	cases := buildFaultBank()
	if len(cases) == 0 {
		fatalf("no cases generated")
	}

	fixtureDir := filepath.Join("eval", "fixtures", "fault-bank")
	casePath := filepath.Join("eval", "cases", "fault-bank.yaml")
	if err := os.MkdirAll(fixtureDir, 0o755); err != nil {
		fatalf("create fixture dir: %v", err)
	}
	if err := os.MkdirAll(filepath.Dir(casePath), 0o755); err != nil {
		fatalf("create case dir: %v", err)
	}

	outCases := make([]eval.EvalCase, 0, len(cases))
	for _, item := range cases {
		fixturePath := filepath.Join(fixtureDir, item.Case.ID+".json")
		if err := eval.WriteFixture(fixturePath, item.Ctx); err != nil {
			fatalf("write fixture %s: %v", item.Case.ID, err)
		}
		item.Case.Fixture = filepath.ToSlash(filepath.Join("..", "fixtures", "fault-bank", item.Case.ID+".json"))
		outCases = append(outCases, item.Case)
	}

	suite := struct {
		Cases []eval.EvalCase `yaml:"cases"`
	}{Cases: outCases}
	data, err := yaml.Marshal(suite)
	if err != nil {
		fatalf("marshal cases yaml: %v", err)
	}
	data = append([]byte("# Generated by scripts/generate_eval_fault_bank.go; edit the generator and rerun.\n"), data...)
	if err := os.WriteFile(casePath, data, 0o644); err != nil {
		fatalf("write %s: %v", casePath, err)
	}
	if err := writeDemoManifests(cases); err != nil {
		fatalf("write demo manifests: %v", err)
	}

	fmt.Printf("generated %d fault-bank cases in %s and %s\n", len(outCases), fixtureDir, casePath)
	fmt.Printf("generated kubectl demo manifests in %s\n", filepath.Join("demo", "fault-bank"))
}

func buildFaultBank() []generatedCase {
	var cases []generatedCase
	cases = append(cases, oomCases()...)
	cases = append(cases, crashLoopCases()...)
	cases = append(cases, pendingCases()...)
	cases = append(cases, imagePullCases()...)
	cases = append(cases, probeCases()...)
	cases = append(cases, initCases()...)
	cases = append(cases, evictedCases()...)
	cases = append(cases, nodeNotReadyCases()...)
	return cases
}

